#!/usr/bin/env node
/**
 * Build a single-EXE Windows installer from a prepared portable release.
 *
 * Prerequisites:
 *   - Inno Setup 6 with ISCC.exe (winget install JRSoftware.InnoSetup)
 *   - A portable release containing data/self-test.json
 *
 * Usage:
 *   DSH_HUB_APP_DIR="<delivery>\release\DSH-Hub-0.1.0-win-x64" \
 *   DSH_HUB_INSTALLER_OUT="<delivery>" \
 *   DSH_HUB_INSTALLER_STAGE="<delivery>\installer\payload" \
 *   npm run installer:win
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(fs.readFileSync(path.join(root, 'package.json'), 'utf8'));
const version = process.env.DSH_HUB_APP_VERSION || pkg.version;
const appDirName = `DSH-Hub-${version}-win-x64`;

const appDirCandidates = [
  process.env.DSH_HUB_APP_DIR,
  path.join(root, 'release', appDirName),
].filter(Boolean);
const appDir = appDirCandidates.find((candidate) => fs.existsSync(path.join(candidate, 'DSH-Hub.exe')));
if (!appDir) {
  console.error('找不到已打包的便携目录。请先 npm run package:zip，或设置 DSH_HUB_APP_DIR。');
  process.exit(1);
}

const outputDir = path.resolve(process.env.DSH_HUB_INSTALLER_OUT || path.join(root, 'release'));
const stageDir = path.resolve(process.env.DSH_HUB_INSTALLER_STAGE || path.join(root, 'installer', 'payload'));
const installerDir = path.join(root, 'installer');
const languageFile = path.join(installerDir, 'ChineseSimplified.isl');
const iconFile = path.join(root, 'assets', 'icon.ico');
const scriptFile = path.join(installerDir, 'DSH-Hub.iss');

for (const [label, file] of [['icon', iconFile], ['language file', languageFile], ['Inno script', scriptFile]]) {
  if (!fs.existsSync(file)) {
    console.error(`缺少 ${label}: ${file}`);
    process.exit(1);
  }
}
const selfTestFile = path.join(appDir, 'data', 'self-test.json');
if (!fs.existsSync(selfTestFile)) {
  console.error(`发布目录缺少自检证据: ${selfTestFile}`);
  process.exit(1);
}
const selfTest = JSON.parse(fs.readFileSync(selfTestFile, 'utf8'));
if (!selfTest.ok || selfTest.isPackaged !== true) {
  console.error(`发布自检未通过 (ok=${selfTest.ok}, isPackaged=${selfTest.isPackaged})`);
  process.exit(1);
}

const isccCandidates = [
  process.env.ISCC,
  path.join(process.env.LOCALAPPDATA || '', 'Programs', 'Inno Setup 6', 'ISCC.exe'),
  path.join(process.env.ProgramFiles || '', 'Inno Setup 6', 'ISCC.exe'),
  path.join(process.env['ProgramFiles(x86)'] || '', 'Inno Setup 6', 'ISCC.exe'),
].filter(Boolean);
const iscc = isccCandidates.find((candidate) => fs.existsSync(candidate));
if (!iscc) {
  console.error('找不到 Inno Setup 的 ISCC.exe。可执行：winget install --id JRSoftware.InnoSetup -e');
  process.exit(1);
}

console.log(`Source:   ${appDir}`);
console.log(`Payload:  ${stageDir}`);
console.log(`Output:   ${outputDir}`);
console.log(`Compiler: ${iscc}`);

fs.rmSync(stageDir, { recursive: true, force: true });
fs.mkdirSync(stageDir, { recursive: true });
copyDirectory(appDir, stageDir);

// Never ship the live portable app's data folder (logs, settings, Chromium
// caches, .running.json). An installer must start from a clean data directory;
// only the self-test evidence is kept.
const stagedData = path.join(stageDir, 'data');
fs.rmSync(stagedData, { recursive: true, force: true });
fs.mkdirSync(path.join(stagedData, 'logs'), { recursive: true });
fs.mkdirSync(path.join(stagedData, 'crashes'), { recursive: true });
fs.copyFileSync(selfTestFile, path.join(stagedData, 'self-test.json'));
fs.writeFileSync(path.join(stagedData, 'README.txt'), [
  'DSH Hub installed data directory.',
  '',
  'self-test.json is generated by the portable build and kept for verification.',
  'Settings, logs, crash reports and backups are created here on first run.',
  '',
].join('\r\n'));

fs.mkdirSync(outputDir, { recursive: true });
const numericVersion = toNumericVersion(version);
const env = {
  ...process.env,
  DSH_HUB_APP_VERSION: version,
  DSH_HUB_VERSION_INFO: numericVersion,
  DSH_HUB_INSTALLER_OUT: outputDir,
  DSH_HUB_PAYLOAD_DIR: stageDir,
  DSH_HUB_ICON: iconFile,
  DSH_HUB_LANG_FILE: languageFile,
};
delete env.ELECTRON_RUN_AS_NODE;

const build = spawnSync(iscc, [scriptFile], {
  cwd: installerDir,
  env,
  stdio: 'inherit',
  windowsHide: true,
});
if (build.status !== 0) {
  console.error(`Inno Setup failed with exit code ${build.status}.`);
  process.exit(build.status || 1);
}

const setup = path.join(outputDir, `DSH-Hub-${version}-Setup.exe`);
if (!fs.existsSync(setup)) {
  console.error(`Inno Setup reported success but ${setup} was not created.`);
  process.exit(1);
}
const size = fs.statSync(setup).size;
const sha256 = crypto.createHash('sha256').update(fs.readFileSync(setup)).digest('hex');
const buildInfo = {
  version,
  generatedAt: new Date().toISOString(),
  source: appDir,
  setup,
  size,
  sha256,
  selfTest: {
    ok: selfTest.ok,
    isPackaged: selfTest.isPackaged,
    electron: selfTest.electron,
    at: selfTest.at,
  },
};
const infoFile = path.join(outputDir, `DSH-Hub-${version}-Setup.json`);
fs.writeFileSync(infoFile, `${JSON.stringify(buildInfo, null, 2)}\n`);
console.log(`Installer: ${setup}`);
console.log(`Size:      ${(size / 1024 / 1024).toFixed(1)} MB`);
console.log(`SHA-256:   ${sha256}`);
console.log(`Metadata:  ${infoFile}`);

function copyDirectory(source, target) {
  fs.mkdirSync(target, { recursive: true });
  for (const entry of fs.readdirSync(source, { withFileTypes: true })) {
    const from = path.join(source, entry.name);
    const to = path.join(target, entry.name);
    if (entry.isDirectory()) copyDirectory(from, to);
    else if (entry.isFile()) fs.copyFileSync(from, to);
  }
}

function toNumericVersion(input) {
  const parts = String(input).split('.').map((part) => Number.parseInt(part, 10) || 0);
  while (parts.length < 4) parts.push(0);
  return parts.slice(0, 4).join('.');
}
